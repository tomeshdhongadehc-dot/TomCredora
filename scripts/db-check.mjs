// Runs the database migrations on a throwaway Postgres (Docker) and attacks the row-level security rules as an
// anonymous visitor and as two different users.   npm run db:check
//
// It touches nothing of yours: the container is created, used and deleted, and nothing here connects to Supabase.
// Requirement: Docker running. The first run downloads the postgres image (~100MB).
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

// supabase/setup.sql (the file you paste into Supabase) is GENERATED from the migrations here, every run, so what is
// tested below is always exactly what gets pasted and the two can never drift apart.
const lf = (f) => readFileSync(f, "utf8").replace(/\r\n/g, "\n").trimEnd();
writeFileSync(
  "supabase/setup.sql",
  [
    "-- TomCredora: complete database setup. Paste this whole file into the Supabase SQL editor and press Run, ONCE.",
    "-- Generated by `npm run db:check` from 0001_init.sql + 0002_user_data.sql. Do not edit it by hand.",
    "-- Running it a second time errors with 'already exists'; that is harmless.",
    "",
    "-- ===== 0001_init.sql =====",
    lf("supabase/migrations/0001_init.sql"),
    "",
    "-- ===== 0002_user_data.sql =====",
    lf("supabase/migrations/0002_user_data.sql"),
    "",
  ].join("\n"),
);

const NAME = "tomcredora-dbcheck";
const IMAGE = "postgres:16-alpine";
const sh = (args, input) => spawnSync("docker", args, { encoding: "utf8", input, maxBuffer: 20_000_000 });

function cleanup() {
  sh(["rm", "-f", NAME]);
}

function fail(msg, detail) {
  console.error(`\n✘ ${msg}`);
  if (detail) console.error(detail.trim().split("\n").slice(-15).join("\n"));
  cleanup();
  process.exit(1);
}

if (sh(["info"]).status !== 0) fail("Docker is not running. Start Docker Desktop and run this again.");
cleanup();
console.log(`Starting a throwaway ${IMAGE} ...`);
const run = sh(["run", "-d", "--rm", "--name", NAME, "-e", "POSTGRES_PASSWORD=check", IMAGE]);
if (run.status !== 0) fail("Could not start Postgres", run.stderr);

/** The postgres image starts a temporary server, then restarts for real. Wait for the end of that setup, not the first answer. */
function waitReady() {
  for (let i = 0; i < 90; i++) {
    const logs = sh(["logs", NAME]);
    const done = /init process complete/.test(`${logs.stdout}${logs.stderr}`);
    if (done && sh(["exec", NAME, "psql", "-U", "postgres", "-tAc", "select 1"]).stdout?.trim() === "1") return;
    spawnSync("node", ["-e", "setTimeout(()=>{},1000)"]);
  }
  fail("Postgres did not become ready in time");
}
waitReady();

function psql(label, file) {
  const r = sh(["exec", "-i", NAME, "psql", "-U", "postgres", "-v", "ON_ERROR_STOP=1", "-q"], readFileSync(file, "utf8"));
  const out = `${r.stdout}\n${r.stderr}`;
  if (r.status !== 0) fail(`${label} failed`, out);
  return out;
}

psql("Supabase stub", "supabase/tests/00_supabase_stub.sql");
console.log("✓ Supabase stand-in created");
psql("Migration 0001_init.sql", "supabase/migrations/0001_init.sql");
console.log("✓ 0001_init.sql applied with no errors");
psql("Migration 0002_user_data.sql", "supabase/migrations/0002_user_data.sql");
console.log("✓ 0002_user_data.sql applied with no errors");

// the single-paste file must give the same result as the two migrations (fresh database)
cleanup();
const second = sh(["run", "-d", "--rm", "--name", NAME, "-e", "POSTGRES_PASSWORD=check", IMAGE]);
if (second.status !== 0) fail("Could not restart Postgres", second.stderr);
waitReady();
psql("Supabase stub", "supabase/tests/00_supabase_stub.sql");
psql("supabase/setup.sql (the single-paste file)", "supabase/setup.sql");
console.log("✓ supabase/setup.sql applies cleanly on a fresh database");

const out = psql("Security checks", "supabase/tests/20_security.sql");
const lines = out.split("\n").filter((l) => /PASS:|FAIL:/.test(l)).map((l) => l.replace(/^.*?(PASS|FAIL):/, "$1:").trim());
for (const l of lines) console.log(`  ${l.startsWith("PASS") ? "✓" : "✘"} ${l.replace(/^(PASS|FAIL): /, "")}`);
const failed = lines.filter((l) => l.startsWith("FAIL"));
cleanup();
if (failed.length || !lines.length) fail(`${failed.length} security check(s) failed`);
console.log(`\nAll ${lines.length} security checks passed. The container has been removed.`);
